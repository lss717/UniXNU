#!/usr/bin/env python3
"""Generate A540FirmwareBlobs.h from the local vendor firmware cache.

The blobs are proprietary and are never committed. They are read from
.cache/firmware/a540 (or --input) and emitted into the build directory so the
A540 bring-up object can copy them into GPU-visible memory.
"""
import argparse
import hashlib
from pathlib import Path

KNOWN = {
    'a530_pm4.fw': ('a02c9be11787472d4ab0173ed8552afbde1f31b1e81bcd87adf1fcea97b6115f', 'a540_fw_pm4'),
    'a530_pfp.fw': ('cc4f2b1cd6b3a9401592e2498ec43b87ba926a23848fa231f417ab08df9c47ba', 'a540_fw_pfp'),
    'a540_gpmu.fw2': ('57d7653c4dcc1130ac2c31512ec7fbb6348613d4bcd99b9b6221e3f9ee52f535', 'a540_fw_gpmu'),
    'a540_zap.mdt': ('530c0a89308b275231bbcbaf0eb3104cccbb885e9014993aea5d6d81aa9063be', 'a540_fw_zap_mdt'),
    'a540_zap.elf': ('efac89c56dd23caad79ba247f61c54a2624b4e0f61c391d2c92f3065c22a6f40', 'a540_fw_zap_elf'),
}


def emit(path: Path, data: bytes, name: str):
    lines = [f'static const unsigned char {name}[] = {{']
    for i in range(0, len(data), 16):
        chunk = ','.join(f'0x{b:02x}' for b in data[i:i + 16])
        lines.append('    ' + chunk + ',')
    lines.append('};')
    lines.append(f'static const unsigned int {name}_size = {len(data)};')
    lines.append('')
    path.write_text('\n'.join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--input', type=Path,
                    default=Path('.cache/firmware/a540'))
    ap.add_argument('--output', type=Path,
                    default=Path('build/native-legacy-display/A540FirmwareBlobs.h'))
    args = ap.parse_args()

    parts = ['// Generated by scripts/gen-a540-firmware.py. Vendor blobs, do not commit.',
             '#pragma once', '#include <stdint.h>', '']
    for filename, (sha, name) in KNOWN.items():
        p = args.input / filename
        if not p.is_file():
            raise SystemExit(f'missing {p}')
        data = p.read_bytes()
        got = hashlib.sha256(data).hexdigest()
        if got != sha:
            raise SystemExit(f'{filename}: sha256 {got} != {sha}')
        parts.append(f'// {filename}: {len(data)} bytes, {got}')
        parts.append(f'static const unsigned char {name}[] = {{')
        for i in range(0, len(data), 16):
            parts.append('    ' + ','.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
        parts.append('};')
        parts.append(f'static const unsigned int {name}_size = {len(data)};')
        parts.append('')

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(parts))
    print(f'wrote {args.output} ({args.output.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
